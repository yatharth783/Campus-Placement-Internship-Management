const mongoose = require('mongoose');

const applicationSchema = new mongoose.Schema(
  {
    studentId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'User',
      required: true
    },
    jobId: {
      type: mongoose.Schema.Types.ObjectId,
      ref: 'Job',
      required: true
    },
    resumePath: {
      type: String,
      default: ''
    },
    status: {
      type: String,
      enum: ['Applied', 'Under Review', 'Shortlisted', 'Rejected', 'Selected'],
      default: 'Applied'
    },
    appliedAt: {
      type: Date,
      default: Date.now
    },
    recruiterRemarks: {
      type: String,
      default: '',
      trim: true
    },
    similarityScore: {
      type: Number,
      default: null // Decision-support metric generated by ML Assistant
    }
  },
  {
    timestamps: true
  }
);

// Prevent duplicate applications: one application per student per job
applicationSchema.index({ studentId: 1, jobId: 1 }, { unique: true });

module.exports = mongoose.model('Application', applicationSchema);
